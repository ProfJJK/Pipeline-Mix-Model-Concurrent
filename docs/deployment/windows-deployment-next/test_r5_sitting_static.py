def pin_block():
    assert TEXT.count(PIN_BEGIN) == 1 and TEXT.count(PIN_END) == 1, 'one marker pair'
    block = TEXT[TEXT.index(PIN_BEGIN) + len(PIN_BEGIN):TEXT.index(PIN_END)]
    return block


def pin_table():
    block = pin_block()
    assert len(re.findall(r'\$script:Pins\s*=', block)) == 1
    return re.findall(r"^\s*'([^']+)'\s*=\s*'([^']*)'\s*$", block, re.M)


def test_exactly_one_pin_table_with_sha256_values():
    assert len(re.findall(r'\$script:Pins\s*=', TEXT)) == 1, 'the pin table is assigned once, inside the markers'
    entries = pin_table()
