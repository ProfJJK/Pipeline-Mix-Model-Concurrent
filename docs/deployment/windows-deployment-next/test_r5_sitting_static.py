def test_the_pin_handle_denies_writes_and_is_disposed_after_the_child_even_on_a_throw():
    # F6: Assert-R5Pin keeps a deny-write/delete FileStream open until the child exits; the launcher disposes it in finally.
    pin = function_code('Assert-R5Pin')
    opens = re.findall(r"\[IO\.File\]::Open\(([^;]*?)\)", pin)
    assert opens, 'Assert-R5Pin opens the pinned file itself'
    for call in opens:
        assert '[IO.FileAccess]::Read' in call and re.search(r"\[IO\.FileShare\]::Read(?![A-Za-z])", call), 'read access, sharing Read only (no Write, no Delete): ' + call
        assert 'ReadWrite' not in call and 'Delete' not in call, call
    for name, launch in (('Invoke-R5Child', 'Invoke-R5Native'), ('Invoke-R5Attended', 'Start-Process'), ('Invoke-R5Python', 'Invoke-R5Native')):
        body = function_code(name)
        pinned, launched = body.index('Assert-R5Pin'), body.index(launch)
        tries = [m.start() for m in re.finditer(r"\btry\s*\{", body) if pinned < m.start() < launched]
        assert tries, name + ': the launch runs inside a try entered after the pin check'
        assert re.search(r"finally\s*\{[^}]*Dispose", body[launched:]), name + ': the pin stream is disposed in finally after the launch'


