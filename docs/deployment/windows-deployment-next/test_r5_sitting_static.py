def ps_literal(value):
    return str(value).replace("'", "''")


def ps(body, timeout=120):
    return subprocess.run(['powershell.exe', '-NoProfile', '-NonInteractive', '-Command', body], capture_output=True, text=True, timeout=timeout)


_FACTS = None


def facts():
    """One Windows PowerShell 5.1 parse that gathers every structural fact the tests need."""
    global _FACTS
    if _FACTS is None:
        body = (f"$ErrorActionPreference='Stop';$tokens=$null;$errors=$null;"
                f"$ast=[Management.Automation.Language.Parser]::ParseFile('{ps_literal(SCRIPT)}',[ref]$tokens,[ref]$errors);" + r"""
$functions=@($ast.FindAll({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst]},$true)|ForEach-Object {
  [ordered]@{name=$_.Name;start=$_.Extent.StartOffset;end=$_.Extent.EndOffset;text=$_.Extent.Text;top=($_.Parent -eq $ast.EndBlock)}});
$top=@($ast.EndBlock.Statements|ForEach-Object {[ordered]@{type=$_.GetType().Name;text=$_.Extent.Text}});
$commands=@($ast.FindAll({param($n)$n -is [Management.Automation.Language.CommandAst]},$true)|ForEach-Object {
  $fn=$_.Parent;while($null -ne $fn -and -not ($fn -is [Management.Automation.Language.FunctionDefinitionAst])){$fn=$fn.Parent};
  [ordered]@{name=[string]$_.GetCommandName();first=$_.CommandElements[0].Extent.Text;operator=[string]$_.InvocationOperator;text=$_.Extent.Text;start=$_.Extent.StartOffset;
             function=$(if($null -ne $fn){$fn.Name}else{''});
             strings=@($_.CommandElements|Select-Object -Skip 1|ForEach-Object {$_.FindAll({param($n)$n -is [Management.Automation.Language.StringConstantExpressionAst]},$true)}|ForEach-Object {$_.Value})}});
$comments=@($tokens|Where-Object {$_.Kind -eq 'Comment'}|ForEach-Object {[ordered]@{start=$_.Extent.StartOffset;end=$_.Extent.EndOffset}});
$params=@();if($null -ne $ast.ParamBlock){$params=@($ast.ParamBlock.Parameters|ForEach-Object {
  [ordered]@{name=$_.Name.VariablePath.UserPath;default=$(if($null -ne $_.DefaultValue){$_.DefaultValue.Extent.Text}else{$null});attributes=@($_.Attributes|ForEach-Object {$_.Extent.Text})}})};
[ordered]@{errors=@($errors|ForEach-Object {$_.Message});functions=$functions;top=$top;commands=$commands;comments=$comments;params=$params;
  edition=$PSVersionTable.PSEdition;major=$PSVersionTable.PSVersion.Major}|ConvertTo-Json -Depth 6 -Compress
""")
        result = ps(body)
        assert result.returncode == 0, result.stderr
        _FACTS = json.loads(result.stdout)
    return _FACTS


def code_without_comments():
    """The script text with every comment token blanked (offsets preserved)."""
    chars = list(TEXT)
    for comment in facts()['comments']:
        for index in range(comment['start'], comment['end']):
            if chars[index] not in '\r\n':
                chars[index] = ' '
    return ''.join(chars)


def functions():
    return {f['name']: f for f in facts()['functions']}


def function_text(name):
    return functions()[name]['text']


def function_code(name):
    """A function's text with its comments blanked."""
    f = functions()[name]
    return code_without_comments()[f['start']:f['end']]


def reachable(start):
    """Names of the sitting's functions reachable from `start` through calls in function bodies (transitive)."""
    names = set(functions())
    seen, todo = set(), [start]
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        body = function_text(name)
        for other in names:
            if other != name and re.search(r'(?<![\w-])' + re.escape(other) + r'(?![\w-])', body):
                todo.append(other)
    return seen


def calls(name):
    return [c for c in facts()['commands'] if c['name'] == name]


