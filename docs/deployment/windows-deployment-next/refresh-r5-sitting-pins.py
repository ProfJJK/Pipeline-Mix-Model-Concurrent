BEGIN = b'# ---- PIN TABLE (generated by refresh-r5-sitting-pins.py; edit only through it) ----'
END = b'# ---- END PIN TABLE ----'
PLACEHOLDER = 'MISSING-FILE-NOT-PINNED'
DEFAULT_SCRIPT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'RUN_427_R5_SITTING.ps1')

