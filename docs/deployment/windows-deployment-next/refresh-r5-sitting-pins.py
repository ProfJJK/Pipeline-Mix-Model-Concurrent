"""Refresh or check the $script:Pins table of RUN_427_R5_SITTING.ps1 (r5 sitting, 2026-10-11).

Standard library only. Run with the pipeline interpreter in isolated mode:

  C:\\Users\\ansac\\source\\repos\\Pipeline-Mix-Model-Concurrent\\.venv\\Scripts\\python.exe -I refresh-r5-sitting-pins.py [--check]
      [--script <path to RUN_427_R5_SITTING.ps1>]

Resolution rule: every pinned name is a plain file name resolved against the directory that holds the sitting
script (the deployment workspace W). PIN_NAMES below is the authoritative list; the table in the script must hold
exactly these names, in this order, each with the sha256 of the file on disk.

Default mode rewrites ONLY the lines between the two marker lines
  # ---- PIN TABLE (generated by refresh-r5-sitting-pins.py; edit only through it) ----
  # ---- END PIN TABLE ----
keeping the rest of the file byte for byte and the newline convention of the marker line. The script must be ASCII.
A pinned file that does not exist gets the placeholder MISSING-FILE-NOT-PINNED, which the sitting refuses (S0) and
--check reports.

--check changes nothing: it exits 0 when the table equals the files on disk, 1 on any drift (a changed sha, a
missing file or placeholder, a missing, extra or reordered name), printing the drifted names, and 2 when the script
cannot be read or its marker block is malformed.
"""
