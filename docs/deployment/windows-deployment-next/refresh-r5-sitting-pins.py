ENTRY = re.compile(r"^\s*'([^']+)'='([^']*)'\s*$")
NAME_SAFE = re.compile(r'^[A-Za-z0-9._-]+$')


class Malformed(Exception):
    pass


def file_sha256(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def compute_pins(workspace):
    pins = []
    for name in PIN_NAMES:
        if not NAME_SAFE.match(name):
            raise Malformed(f'unsafe pin name {name!r}')
        path = os.path.join(workspace, name)
        pins.append((name, file_sha256(path) if os.path.isfile(path) else PLACEHOLDER))
    return pins


def split_script(raw):
    """Return (head, block, tail, newline): head ends with the BEGIN line, tail starts with the END line."""
    try:
        raw.decode('ascii')
    except UnicodeDecodeError as exc:
        raise Malformed(f'the sitting script is not ASCII (byte offset {exc.start})') from None
    if raw.count(BEGIN) != 1 or raw.count(END) != 1:
        raise Malformed('the sitting script must contain each PIN TABLE marker exactly once')
    begin = raw.index(BEGIN)
    if begin and raw[begin - 1:begin] != b'\n':
        raise Malformed('the BEGIN marker must start a line')
    after_begin = begin + len(BEGIN)
    if raw[after_begin:after_begin + 2] == b'\r\n':
        newline = b'\r\n'
    elif raw[after_begin:after_begin + 1] == b'\n':
        newline = b'\n'
    else:
        raise Malformed('the BEGIN marker must end its line')
    head_end = after_begin + len(newline)
    end = raw.index(END)
    if end < head_end or raw[end - 1:end] != b'\n':
        raise Malformed('the END marker must follow the BEGIN marker on its own line')
    return raw[:head_end], raw[head_end:end], raw[end:], newline


def render_block(pins, newline):
    lines = [b'$script:Pins=@{']
    lines += [("    '%s'='%s'" % (name, sha)).encode('ascii') for name, sha in pins]
    lines.append(b'}')
    return newline.join(lines) + newline


def parse_block(block):
    text = block.decode('ascii').replace('\r\n', '\n')
    lines = [line for line in text.split('\n') if line.strip()]
    if not lines or lines[0].strip() != '$script:Pins=@{' or lines[-1].strip() != '}':
        raise Malformed('the pin block must be $script:Pins=@{ ... } between the markers')
    entries = []
    for line in lines[1:-1]:
        match = ENTRY.match(line)
        if not match:
            raise Malformed(f'unexpected line in the pin block: {line.strip()!r}')
        entries.append((match.group(1), match.group(2)))
    return entries


def drift(current, wanted):
    problems = []
    have = dict(current)
    names = [name for name, _ in current]
    if len(set(names)) != len(names):
        problems.append('duplicate names in the table')
    for name, sha in wanted:
        if sha == PLACEHOLDER:
            problems.append(f'{name}: file missing in the workspace')
        elif name not in have:
            problems.append(f'{name}: not in the table')
        elif have[name] != sha:
            problems.append(f'{name}: table {have[name]} != disk {sha}')
    wanted_names = [name for name, _ in wanted]
    for name in names:
        if name not in wanted_names:
            problems.append(f'{name}: in the table but not a pinned name')
    if not problems and names != wanted_names:
        problems.append('the table order differs from PIN_NAMES')
    return problems


def write_replacing(path, data):
    directory = os.path.dirname(os.path.abspath(path))
    handle, temporary = tempfile.mkstemp(prefix='.pins-', suffix='.tmp', dir=directory)
    try:
        with os.fdopen(handle, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(description='Refresh or check the RUN_427_R5_SITTING.ps1 pin table.')
    parser.add_argument('--check', action='store_true', help='change nothing; exit 1 on any drift')
    parser.add_argument('--script', default=DEFAULT_SCRIPT, help='the sitting script (pins resolve against its folder)')
    args = parser.parse_args(argv)
    script = os.path.abspath(args.script)
    workspace = os.path.dirname(script)
    try:
        with open(script, 'rb') as handle:
            raw = handle.read()
        head, block, tail, newline = split_script(raw)
        current = parse_block(block)
        wanted = compute_pins(workspace)
    except (OSError, Malformed) as exc:
        print(f'REFUSED: {exc}', file=sys.stderr)
        return 2
    problems = drift(current, wanted)
    if args.check:
        if problems:
            print('PIN DRIFT in ' + script)
            for problem in problems:
                print('  ' + problem)
            return 1
        print(f'PINS OK: {len(wanted)} files match the table in {script}')
        return 0
    updated = head + render_block(wanted, newline) + tail
    if updated != raw:
        write_replacing(script, updated)
    missing = [name for name, sha in wanted if sha == PLACEHOLDER]
    print(f'PINS WRITTEN: {len(wanted)} entries ({len(missing)} placeholder(s)) in {script}')
    for name in missing:
        print('  placeholder (file missing): ' + name)
    return 1 if missing else 0


if __name__ == '__main__':
    raise SystemExit(main())
